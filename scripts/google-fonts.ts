// Writes core/google-fonts.ts: every Google Fonts family with its category and weights, so code
// can tell a real Google Font from a guess and load it by name. Data from the google-font-metadata
// npm package (data/google-fonts-v2.json). Run: npx tsx scripts/google-fonts.ts <path to that json>
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) throw new Error("Pass the path to google-font-metadata's data/google-fonts-v2.json.");
const data = JSON.parse(readFileSync(src, "utf8")) as Record<string, { family: string; category: string; weights: number[]; subsets: string[] }>;
const CAT: Record<string, string> = { "sans-serif": "s", serif: "r", display: "d", handwriting: "h", monospace: "m" };
const rows = Object.values(data)
  .filter((f) => f.subsets.includes("latin") && CAT[f.category])
  .sort((a, b) => a.family.localeCompare(b.family))
  .map((f) => `${f.family}|${CAT[f.category]}|${f.weights.join(",")}`);
const out = `// Generated by scripts/google-fonts.ts from google-font-metadata. Do not edit by hand.
// One row per Google Fonts family with Latin letters: "Family|category|weights", where category is
// s sans-serif, r serif, d display, h handwriting, m monospace.
export const GOOGLE_FONT_ROWS = ${JSON.stringify(rows.join("\n"))};
`;
writeFileSync(new URL("../core/google-fonts.ts", import.meta.url), out);
console.log(`${rows.length} families`);
